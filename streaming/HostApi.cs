using System;
using System.IO;
using System.Net;
using System.Security.Cryptography.X509Certificates;
using System.Text;
using System.Runtime.InteropServices;

namespace Cadrivect.Streaming {
    public static class HostApi {
        [DllImport("user32.dll", CharSet = CharSet.Unicode)]
        private static extern IntPtr FindWindowEx(IntPtr parent, IntPtr after, string className, string title);
        [DllImport("user32.dll")]
        private static extern uint GetWindowThreadProcessId(IntPtr window, out uint processId);
        [DllImport("user32.dll")]
        private static extern bool PostMessage(IntPtr window, uint message, IntPtr wParam, IntPtr lParam);

        public static bool RequestStop(int processId) {
            // This window is the graceful Windows shutdown entry point in the pinned Sunshine build.
            IntPtr window = IntPtr.Zero;
            while ((window = FindWindowEx(IntPtr.Zero, window, "SunshineSessionMonitorClass", null)) != IntPtr.Zero) {
                uint owner;
                GetWindowThreadProcessId(window, out owner);
                if (owner == processId) return PostMessage(window, 0x0016, new IntPtr(1), IntPtr.Zero);
            }
            return false;
        }

        // Only send the management secret to the certificate generated by our own host.
        public static string Request(string url, string certificatePath, string password, string json) {
            using (var expected = new X509Certificate2(certificatePath)) {
                var request = (HttpWebRequest)WebRequest.Create(url);
                request.Proxy = null;
                request.AllowAutoRedirect = false;
                request.Timeout = 15000;
                request.ReadWriteTimeout = 15000;
                request.ServerCertificateValidationCallback = (sender, cert, chain, errors) =>
                    cert != null && String.Equals(cert.GetRawCertDataString(), expected.GetRawCertDataString(), StringComparison.Ordinal);
                request.Headers[HttpRequestHeader.Authorization] = "Basic " +
                    Convert.ToBase64String(Encoding.UTF8.GetBytes("lumarelay:" + password));
                if (json != null) {
                    byte[] body = Encoding.UTF8.GetBytes(json);
                    request.Method = "POST";
                    request.ContentType = "application/json";
                    request.ContentLength = body.Length;
                    using (var output = request.GetRequestStream()) output.Write(body, 0, body.Length);
                }
                HttpWebResponse response;
                try { response = (HttpWebResponse)request.GetResponse(); }
                catch (WebException ex) {
                    if (ex.Response != null) ex.Response.Close();
                    throw;
                }
                using (response)
                using (var reader = new StreamReader(response.GetResponseStream())) {
                    if ((int)response.StatusCode != 200) throw new IOException("Host management returned " + (int)response.StatusCode);
                    return reader.ReadToEnd();
                }
            }
        }
    }
}
